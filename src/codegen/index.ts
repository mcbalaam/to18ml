import { placeholdersOf } from "../core/interpolate";
import { isPlural } from "../core/plural";
import type { FlatMessages } from "../core/types";

export interface CodegenOptions {
  /** Locale whose structure is authoritative. */
  defaultLocale: string;
  /** Package name in generated imports. */
  packageName?: string;
  /** Emit per-namespace output + lazy loader. */
  split?: boolean;
}

export interface GeneratedFiles {
  [path: string]: string;
}

interface KeyInfo {
  key: string;
  plural: boolean;
  placeholders: string[];
}

const IDENT_RE = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function objectKey(name: string): string {
  return IDENT_RE.test(name) ? name : JSON.stringify(name);
}

const RESERVED_WORDS = new Set([
  "in", "if", "do", "for", "var", "let", "new", "try", "case", "true", "null",
  "this", "void", "with", "enum", "class", "const", "break", "catch", "throw",
  "while", "yield", "await", "delete", "export", "import", "return", "typeof",
  "switch", "default", "extends", "finally", "continue", "debugger", "function",
  "instanceof", "super", "else", "false",
]);

/** `"ru-RU"` -> `"ruRU"`, `"en"` -> `"en"`, `"in"` -> `"in_"`. */
export function localeIdent(locale: string): string {
  const parts = locale.split(/[^A-Za-z0-9]+/).filter(Boolean);
  const head = parts.shift() ?? "locale";
  const ident = head + parts.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join("");
  if (RESERVED_WORDS.has(ident)) return `${ident}_`;
  return /^[A-Za-z_$]/.test(ident) ? ident : `_${ident}`;
}

/** Union of keys and per-key structure across locales. */
export function analyze(locales: Record<string, FlatMessages>): KeyInfo[] {
  const keys = new Set<string>();
  for (const dict of Object.values(locales)) {
    for (const key of Object.keys(dict)) keys.add(key);
  }

  const infos: KeyInfo[] = [];
  for (const key of [...keys].sort()) {
    const names = new Set<string>();
    let plural = false;
    for (const dict of Object.values(locales)) {
      const message = dict[key];
      if (message === undefined) continue;
      if (isPlural(message)) plural = true;
      for (const name of placeholdersOf(message)) names.add(name);
    }
    infos.push({ key, plural, placeholders: [...names].sort() });
  }
  return infos;
}

function renderArgsEntry(info: KeyInfo): string | undefined {
  const args: string[] = [];
  if (info.plural) args.push("count: number");
  for (const name of info.placeholders) {
    if (info.plural && name === "count") continue;
    args.push(`${objectKey(name)}: string | number`);
  }
  if (args.length === 0) return undefined;
  return `{ ${args.join("; ")} }`;
}

function renderSchema(
  infos: KeyInfo[],
  packageName: string,
): string {
  const keys = infos.map((info) => info.key);
  const keyLines =
    keys.length === 0
      ? "    never"
      : keys.map((key) => `    | ${JSON.stringify(key)}`).join("\n");

  const argLines = infos
    .map((info) => {
      const args = renderArgsEntry(info);
      return args === undefined
        ? undefined
        : `    ${JSON.stringify(info.key)}: ${args};`;
    })
    .filter((line): line is string => line !== undefined);

  const pluralKeys = infos.filter((info) => info.plural).map((info) => info.key);
  const pluralLines =
    pluralKeys.length === 0
      ? "  never"
      : pluralKeys.map((key) => `    | ${JSON.stringify(key)}`).join("\n");

  return `// AUTO-GENERATED by to18ml. Do not edit.
import type { MessageSchema } from ${JSON.stringify(packageName)};

export interface Messages extends MessageSchema {
  keys:
${keyLines};
  args: {
${argLines.join("\n")}
  };
  plural:
${pluralLines};
}

export type MessageKey = Messages["keys"];
`;
}

function buildTree(keys: string[]): Record<string, unknown> {
  const root: Record<string, unknown> = {};
  for (const key of keys) {
    const parts = key.split(".");
    let node = root;
    for (let i = 0; i < parts.length - 1; i += 1) {
      const part = parts[i] as string;
      const existing = node[part];
      if (existing !== undefined && typeof existing === "object") {
        node = existing as Record<string, unknown>;
      } else {
        const next: Record<string, unknown> = {};
        node[part] = next;
        node = next;
      }
    }
    node[parts[parts.length - 1] as string] = key;
  }
  return root;
}

function renderTree(node: Record<string, unknown>, depth: number): string {
  const indent = "  ".repeat(depth);
  const entries = Object.entries(node);
  if (entries.length === 0) return "{}";
  const lines = entries.map(([name, value]) => {
    const rendered =
      typeof value === "string"
        ? JSON.stringify(value)
        : renderTree(value as Record<string, unknown>, depth + 1);
    return `${indent}${objectKey(name)}: ${rendered},`;
  });
  return `{\n${lines.join("\n")}\n${"  ".repeat(depth - 1)}}`;
}

function renderMsgs(infos: KeyInfo[]): string {
  const tree = buildTree(infos.map((info) => info.key));
  const body = renderTree(tree, 1);
  return `// AUTO-GENERATED by to18ml. Do not edit.
export const msgs = ${body} as const;
`;
}

function renderIndex(
  localeNames: string[],
  options: Required<Pick<CodegenOptions, "defaultLocale" | "packageName" | "split">>,
  namespaceFiles: string[],
): string {
  const { defaultLocale, packageName, split } = options;

  if (split) {
    const known = namespaceFiles
      .map((file) => `  ${JSON.stringify(file)},`)
      .join("\n");
    return `// AUTO-GENERATED by to18ml. Do not edit.
import type { FlatMessages } from ${JSON.stringify(packageName)};

export const defaultLocale = ${JSON.stringify(defaultLocale)};

export type { Messages, MessageKey } from "./schema";
export { msgs } from "./msgs";

const namespaceFiles: ReadonlySet<string> = new Set([
${known}
]);

export async function loadNamespace(
  locale: string,
  namespace: string,
): Promise<FlatMessages> {
  const file = \`\${locale}/\${namespace}\`;
  if (!namespaceFiles.has(file)) {
    throw new Error(\`to18ml: unknown namespace "\${file}"\`);
  }
  const mod = await import(\`./namespaces/\${file}\`);
  return mod.default;
}
`;
  }

  const imports = localeNames
    .map(
      (locale) =>
        `import ${localeIdent(locale)} from ${JSON.stringify(`./messages/${locale}`)};`,
    )
    .join("\n");

  const entries = localeNames
    .map((locale) => `  ${JSON.stringify(locale)}: ${localeIdent(locale)},`)
    .join("\n");

  return `// AUTO-GENERATED by to18ml. Do not edit.
import type { FlatMessages } from ${JSON.stringify(packageName)};
${imports}

export const messages: Record<string, FlatMessages> = {
${entries}
};

export const defaultLocale = ${JSON.stringify(defaultLocale)};

export type { Messages, MessageKey } from "./schema";
export { msgs } from "./msgs";
`;
}

/** Emit a baked locale as a typed TS module. */
function renderMessages(messages: FlatMessages, packageName: string): string {
  return `// AUTO-GENERATED by to18ml. Do not edit.
import type { FlatMessages } from ${JSON.stringify(packageName)};

const messages: FlatMessages = ${JSON.stringify(messages, null, 2)};

export default messages;
`;
}

/** Bucket keys by their first segment. */
export function splitNamespaces(
  messages: FlatMessages,
): Record<string, FlatMessages> {
  const namespaces: Record<string, FlatMessages> = {};
  for (const [key, value] of Object.entries(messages)) {
    const dot = key.indexOf(".");
    const namespace = dot === -1 ? "" : key.slice(0, dot);
    const bucket = namespaces[namespace] ?? (namespaces[namespace] = {});
    bucket[key] = value;
  }
  return namespaces;
}

/** Generate every file: schema, `msgs`, the `index.ts` barrel, and baked TS modules. */
export function generate(
  locales: Record<string, FlatMessages>,
  options: CodegenOptions,
): GeneratedFiles {
  const resolved = {
    defaultLocale: options.defaultLocale,
    packageName: options.packageName ?? "to18ml",
    split: options.split ?? false,
  };
  const localeNames = Object.keys(locales).sort();
  const infos = analyze(locales);

  const files: GeneratedFiles = {
    "schema.d.ts": renderSchema(infos, resolved.packageName),
    "msgs.ts": renderMsgs(infos),
  };
  const namespaceFiles: string[] = [];

  for (const [locale, messages] of Object.entries(locales)) {
    if (!resolved.split) {
      files[`messages/${locale}.ts`] = renderMessages(messages, resolved.packageName);
      continue;
    }
    for (const [namespace, bucket] of Object.entries(splitNamespaces(messages))) {
      // Every compiled key contains a dot, so a namespace is always present.
      if (namespace === "") {
        throw new Error(
          `to18ml: cannot split locale "${locale}": found a key without a namespace`,
        );
      }
      namespaceFiles.push(`${locale}/${namespace}`);
      files[`namespaces/${locale}/${namespace}.ts`] = renderMessages(
        bucket,
        resolved.packageName,
      );
    }
  }

  files["index.ts"] = renderIndex(localeNames, resolved, namespaceFiles);
  return files;
}
